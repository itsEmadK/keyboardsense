#!/usr/bin/env python3
"""Embed a fixed allowlist of web files: the payload needs no web-root uploads."""
import mimetypes
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parents[1] / 'web'
output = pathlib.Path(sys.argv[1])
output.parent.mkdir(parents=True, exist_ok=True)
allowed = {'.html', '.css', '.js', '.mjs', '.svg', '.png', '.txt'}
assets = sorted(p for p in root.rglob('*') if p.is_file() and p.suffix in allowed)
with output.open('w') as f:
    f.write('/* Generated by tools/embed_web.py. See web/CREDITS.txt. */\n#include "web.h"\n')
    for i, path in enumerate(assets):
        data = path.read_bytes()
        f.write(f'static const unsigned char asset_{i}[] = {{\n')
        for offset in range(0, len(data), 24):
            f.write(','.join(str(b) for b in data[offset:offset+24]) + ',\n')
        f.write('};\n')
    f.write('const KsWebAsset ks_web_assets[] = {\n')
    for i, path in enumerate(assets):
        name = '/' + path.relative_to(root).as_posix()
        mime = mimetypes.guess_type(path)[0] or 'application/octet-stream'
        if path.suffix in {'.js', '.mjs'}:
            mime = 'text/javascript'
        f.write(f'{{"{name}", "{mime}", asset_{i}, sizeof(asset_{i})}},\n')
    f.write('};\nconst size_t ks_web_asset_count = sizeof(ks_web_assets) / sizeof(*ks_web_assets);\n')
