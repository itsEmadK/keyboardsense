#!/usr/bin/env python3
"""Embed the Media launcher metadata and an original, code-drawn 512px icon."""
# SPDX-License-Identifier: GPL-3.0-only
import json
import pathlib
import re
import struct
import sys
import zlib

ROOT = pathlib.Path(__file__).resolve().parents[1]


def metadata():
    data = (ROOT / 'media/param.json').read_bytes()
    param = json.loads(data)
    if (not re.fullmatch(r'KBSN[0-9]{5}', param['titleId']) or
            param['applicationCategoryType'] != 65536 or
            param['deeplinkUri'] != 'http://127.0.0.1:1405/' or
            param['localizedParameters']['en-US']['titleName'] != 'KeyboardSense'):
        raise ValueError('unexpected KeyboardSense Media launcher metadata')
    return param, data


def icon_png():
    size = 512
    pixels = bytearray(bytes((23, 29, 25, 255)) * size * size)

    def box(x, y, width, height, color, radius=0):
        for py in range(y, y + height):
            for px in range(x, x + width):
                # Rounded corners without an external image/font dependency.
                dx = max(x + radius - px, 0, px - (x + width - 1 - radius))
                dy = max(y + radius - py, 0, py - (y + height - 1 - radius))
                if dx * dx + dy * dy > radius * radius:
                    continue
                start = (py * size + px) * 4
                pixels[start:start + 4] = bytes(color)

    lime, border, dark = (213, 244, 126, 255), (95, 116, 74, 255), (23, 29, 25, 255)
    for x, y in [(64, 65), (104, 65), (104, 105)]:
        box(x, y, 30, 30, lime, 6)
    box(64, 105, 30, 30, (81, 101, 56, 255), 6)
    box(57, 210, 305, 184, border, 18)
    box(62, 215, 295, 174, dark, 14)
    for row in range(3):
        for column in range(7):
            color = lime if (row, column) in [(0, 1), (1, 0), (1, 1), (1, 2)] else border
            box(78 + column * 38, 232 + row * 38, 29, 29, color, 5)
    box(115, 348, 174, 23, border, 5)
    box(386, 229, 74, 151, border, 34)
    box(391, 234, 64, 141, dark, 29)
    box(420, 235, 6, 46, border, 1)
    box(392, 285, 62, 5, border)
    box(417, 250, 12, 20, lime, 5)

    def chunk(kind, payload):
        return (struct.pack('>I', len(payload)) + kind + payload +
                struct.pack('>I', zlib.crc32(kind + payload)))

    rows = b''.join(b'\0' + pixels[y * size * 4:(y + 1) * size * 4] for y in range(size))
    return (b'\x89PNG\r\n\x1a\n' +
            chunk(b'IHDR', struct.pack('>IIBBBBB', size, size, 8, 6, 0, 0, 0)) +
            chunk(b'IDAT', zlib.compress(rows, 9)) + chunk(b'IEND', b''))


def main():
    param, data = metadata()
    output = pathlib.Path(sys.argv[1])
    output.parent.mkdir(parents=True, exist_ok=True)
    icon = icon_png()
    output.with_name('media-icon.png').write_bytes(icon)
    with output.open('w') as f:
        f.write('/* Generated by tools/embed_media.py. SPDX-License-Identifier: GPL-3.0-only */\n')
        f.write('#include "media.h"\n#include "web.h"\n')
        f.write('_Static_assert(KS_WEB_PORT == 1405, "Media shortcut must match web port");\n')
        f.write(f'const char ks_media_title_id[] = "{param["titleId"]}";\n')
        for name, asset in [('param', data), ('icon', icon)]:
            f.write(f'const unsigned char ks_media_{name}[] = {{\n')
            for offset in range(0, len(asset), 24):
                f.write(','.join(str(b) for b in asset[offset:offset + 24]) + ',\n')
            f.write(f'}};\nconst size_t ks_media_{name}_size = sizeof(ks_media_{name});\n')


if __name__ == '__main__':
    main()
